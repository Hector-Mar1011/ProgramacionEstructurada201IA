# Ejemplo de uso de operadores de aritmetica en python 

def operadores():
        
    # Suma
    suma = 5 + 3

    # Resta
    resta = 10 - 4

    # Multiplicación
    multiplicacion = 6 * 7

    # Division
    Division_Entera = 10 // 3

    # Modulo
    modulo = 10 % 3

    #potenciación
    potenciacion = 2 ** 3

    print(f"El resultado de su suma es: {suma}")
    print(f"El resultado de su resta es: {resta}")
    print(f"El resultado de su multiplicación es: {multiplicacion}")
    print(f"El resultado de su división entera es: {Division_Entera}")
    print(f"El resultado de su modulo es: {modulo}")
    print(f"El resultado de su potenciación es: {potenciacion}")


def main():
    operadores()
   
    
    
if __name__ == "__main__":
    main()





